import {chromium} from "playwright";
import fs from "node:fs";
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on("pageerror",error=>errors.push(error.stack));
try {
  await page.goto("http://localhost:30014",{waitUntil:"networkidle"});
  await page.locator('[name="username"]').fill("Gamemaster");await page.locator('button[name="join"]').click();
  await page.waitForFunction(()=>game.ready&&game.runeterra?.tickActor);
  const results=await page.evaluate(async()=>{
    const results=[];const assert=(label,value)=>{if(!value)throw new Error(label);results.push(label);};
    const equipment=game.packs.get("jdr-runeterra.equipment"),bestiary=game.packs.get("jdr-runeterra.bestiary");
    await equipment.getDocuments();await bestiary.getDocuments();
    const galidarium=equipment.find(d=>d.name==="Galidarium");
    assert("clean weapon name and subtype",galidarium?.system.weaponType==="Sceptre - 1 Main");
    assert("weapon subfolders",equipment.folders.some(f=>f.name==="Épées")&&equipment.folders.some(f=>f.name==="Lances")&&equipment.folders.some(f=>f.name==="Boucliers"));
    assert("split creature group",bestiary.some(d=>d.name==="SPNETYRR")&&bestiary.some(d=>d.name==="DORDÜMND")&&bestiary.some(d=>d.name==="TREVNSKAALD"));
    const shark=bestiary.find(d=>d.system.biography.includes("Pince-Requins"));
    assert("armor does not populate RM",shark.system.armor.rating===5&&shark.system.magicResistance.rating===0);
    assert("empty taming does not consume environment",shark.system.taming==="");
    await equipment.render({force:true});
    assert("compendium window title has no suffix",!equipment.apps[Object.keys(equipment.apps)[0]]?.title?.endsWith(".title"));
    const a=await Actor.create({name:"Reported bugs verification",type:"character"});
    globalThis.rtBugActor=a;
    await a.update({"system.attributes.agility.base":80});
    assert("second 80 rejected",a.system.attributes.agility.base===50);
    await a.update({"system.attributes.mental.base":20});
    assert("mandatory 10 rejected",a.system.attributes.mental.base===10);
    await a.update({"system.attributes.force.base":50,"system.attributes.agility.base":80});
    assert("moving unique 80 allowed atomically",a.system.attributes.agility.base===80&&a.system.attributes.force.base===50);
    await a.sheet.render({force:true});
    await galidarium.sheet.render({force:true});globalThis.rtBugItem=galidarium;
    const creature=await Actor.create(shark.toObject());globalThis.rtBugCreature=creature;await creature.sheet.render({force:true});
    return results;
  });
  await page.waitForSelector('.rt-item prose-mirror');
  await page.evaluate(()=>rtBugActor.sheet.bringToFront());
  const allocation=page.locator('.rt-actor').filter({has:page.locator('[name="system.permanentMalus"]')});
  await allocation.locator('[name="system.attributes.force.base"]').fill("80");
  await allocation.locator('[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('#notifications')?.textContent.includes("80"));
  if(await page.evaluate(()=>rtBugActor.system.attributes.force.base)!==50)throw new Error("invalid allocation saved from form");
  await allocation.locator('[name="system.attributes.agility.base"]').fill("50");
  await allocation.locator('[type="submit"]').click();
  await page.waitForFunction(()=>rtBugActor.system.attributes.force.base===80&&rtBugActor.system.attributes.agility.base===50);
  results.push("sheet save rejects invalid and accepts complete allocation");
  await allocation.locator('[data-action="validate"]').click();
  await page.waitForFunction(()=>rtBugActor.system.validated);
  results.push("creation validation includes pending form values");
  await page.evaluate(async()=>{
    await rtBugActor.update({"system.attributes.agility.base":80,"system.attributes.endurance.base":90,"system.attributes.force.bonus":15});
    if(!rtBugActor.system.validated||rtBugActor.system.attributes.agility.base!==80||rtBugActor.system.attributes.endurance.base!==90||rtBugActor.system.effective.force!==95)throw new Error("progression incorrectly constrained by creation allocation");
  });
  await allocation.locator('[name="system.attributes.perception.base"]').fill("85");
  await allocation.locator('[type="submit"]').click();
  await page.waitForFunction(()=>rtBugActor.system.attributes.perception.base===85&&rtBugActor.system.validated);
  if(await allocation.locator('.rt-warning').count())throw new Error("creation warnings shown after progression");
  results.push("validated characters save multiple base attributes at 80+ and bonus totals above 80");
  const checks=await page.evaluate(()=>{
    const item=rtBugItem.sheet.element,creature=rtBugCreature.sheet.element,actor=rtBugActor.sheet.element;
    const checkbox=item.querySelector('input[type="checkbox"]');
    return {richText:item.querySelector('prose-mirror').textContent.includes("Galidarium"),rawTextarea:!!item.querySelector('textarea[name="system.description"]'),armor:!!creature.querySelector('[name="system.armor.rating"]'),rm:!!creature.querySelector('[name="system.magicResistance.rating"]'),save:!!actor.querySelector('[type="submit"]'),checkbox:getComputedStyle(checkbox,"::before").content,checkboxAppearance:getComputedStyle(checkbox).appearance};
  });
  if(!checks.richText||checks.rawTextarea||!checks.armor||!checks.rm||!checks.save||!["none","normal"].includes(checks.checkbox)||checks.checkboxAppearance!=="auto")throw new Error(JSON.stringify(checks));
  await page.screenshot({path:"test-results/reported-bugs.png",fullPage:true});
  await page.evaluate(async()=>{await rtBugActor.delete();await rtBugCreature.delete();});
  if(errors.length)throw new Error(errors.join("\n"));
  fs.writeFileSync("test-results/reported-bugs.json",JSON.stringify({results,checks,errors},null,2));
  console.log(JSON.stringify({results,checks,errors}));
}finally{await browser.close();}
